export const slotsOf = (diet) => diet.slots || DEFAULT_SLOTS

// co-prime steps per slot keep combos fresh across 30 days
const STEP = { b: 3, l: 4, d: 5, s: 2 }
const OFF = { b: 0, l: 2, d: 1, s: 3 }

/** Day n (1..30) of a diet's plan. */
export function dietDay(diet, n) {
  const type = diet.cycle ? diet.cycle[(n - 1) % diet.cycle.length] : null
  const meals = slotsOf(diet).map((slot) => {
    let pool = diet.pools[slot.k] || []
    if (type) {
      const typed = pool.filter((x) => x.tag === type)
      if (typed.length) pool = typed
    }
    const i = ((n - 1) * STEP[slot.k] + OFF[slot.k] + Math.floor((n - 1) / pool.length)) % pool.length
    return { ...slot, ...pool[i] }
  })
  return { n, week: Math.ceil(n / 7), type, meals, kcal: meals.reduce((s, x) => s + (x.k || 0), 0) }
}

